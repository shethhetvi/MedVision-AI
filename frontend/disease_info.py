    st.write("**Symptoms:** Cough, fever, chills, and difficulty breathing.")
    st.write("**Causes:** Bacteria, viruses, or fungi infections in the lungs.")
    st.write("**Risk Factors:** Age (under 2 or over 65), weakened immune system, smoking.")
